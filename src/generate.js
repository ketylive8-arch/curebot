function firstSentence(s) {
  const t = String(s || "").split(/[.\n!?]/)[0].trim();
  return t ? t + "." : "";
}

export function detectIndustry(p) {
  const blob = `${p.businessType || ""} ${p.about || ""} ${p.businessName || ""}`.toLowerCase();
  let best = null, hits = 0;
  for (const ind of INDUSTRIES) {
    const n = ind.words.filter(w => blob.includes(w)).length;
    if (n > hits) { best = ind; hits = n; }
  }
  return best;
}

/** תבניות חכמות — חינמי, בלי AI. */
export function templateDraft(p) {
  const name = p.businessName || "העסק";
  const common = [
    ["מה אתם עושים?", p.about ? p.about.trim() : TODO("משפט-שניים על העסק")],
    ["מה שעות הפעילות?", p.hours ? `שעות הפעילות: ${p.hours}` : TODO("שעות פעילות")],
    ["כמה זה עולה?", TODO("מחיר / טווח מחירים — או 'המחיר תלוי ב…, נשמח לתת הצעה'")]
  ];
  if (p.address) common.push(["איפה אתם נמצאים?", `אנחנו ב${p.address}`]);
  if (p.bookingLink) common.push(["איך קובעים?", `אפשר לקבוע כאן, בכמה לחיצות: ${p.bookingLink}`]);
  const ind = detectIndustry(p);
  const specific = ind ? ind.faq(p) : [["למי השירות מתאים?", TODO("למי מתאים")]];
  const faq = [...common, ...specific].map(([q, a]) => ({ q, a }));
  return {
    faq,
    greeting: `היי! כאן ${name} 👋 איך אפשר לעזור?`,
    handoffText: `בשמחה — אני מעבירה את הפנייה ל${name}, ונחזור אלייך בהקדם 🙏`,
    source: "templates",
    industry: ind?.key || "general"
  };
}

const AI_SYSTEM = `את/ה כותב/ת תשובות מוכנות לבוט וואטסאפ של עסק קטן בישראל.
כתוב/כתבי בעברית טבעית, חמה וקצרה (1-3 משפטים לתשובה), בגוף ראשון של העסק.
חוקים:
- רק לפי המידע שקיבלת. אסור להמציא מחירים, שעות, כתובות, שירותים או הבטחות.
- כשחסר מידע לתשובה — כתוב/י במקום המידע "[להשלים: <מה חסר>]".
- 8 שאלות שלקוחות של עסק כזה באמת שואלים, בניסוח של לקוח.
החזר/י JSON בלבד בפורמט: {"faq":[{"q":"...","a":"..."}],"greeting":"...","handoffText":"..."}`;

/** יוצר טיוטה: AI אם יש קרדיט, אחרת תבניות. לעולם לא נכשל. */
export async function generateDraft(p) {
  if (aiState().mode === "openai") {
    const info = [
      `שם העסק: ${p.businessName || "-"}`, `סוג העסק: ${p.businessType || "-"}`, `על העסק: ${p.about || "-"}`,
      `שעות: ${p.hours || "-"}`, `כתובת: ${p.address || "-"}`, `קישור לקביעה: ${p.bookingLink || "-"}`, `אתר: ${p.website || "-"}`
    ].join("\n");
    try {
      const raw = await aiText(AI_SYSTEM, info);
      const json = JSON.parse(raw.slice(raw.indexOf("{"), raw.lastIndexOf("}") + 1));
      const faq = (json.faq || []).filter(f => f && f.q && f.a).slice(0, 12).map(f => ({ q: String(f.q), a: String(f.a) }));
      if (faq.length >= 3) return { faq, greeting: json.greeting || "", handoffText: json.handoffText || "", source: "ai" };
    } catch (e) { console.log("[generate] AI נכשל — עוברים לתבניות:", String(e.message).slice(0, 80)); }
  }
  return templateDraft(p);
}
