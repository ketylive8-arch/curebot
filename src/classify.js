/**
 * extraWords: מילים של העסק (מהפרופיל) שגם הן מסמנות פנייה רלוונטית.
 * מחזיר spam | auto | promo | irrelevant | normal.
 *  auto = שליח / קוד אימות / אישור תשלום / הודעה אוטומטית — לא עונים.
 *  irrelevant = הודעה ראשונה ארוכה שאין בה שום קשר לפעילות העסק — לא עונים.
 *  הודעה קצרה ("היי", "שאלה", "אפשר פרטים?") נחשבת רלוונטית — כך לא מפספסים לידים.
 */
export function classifyMessage(text, extraWords = []) {
  const t = String(text || "").toLowerCase();
  if (!t.trim()) return "normal";
  const urls = (t.match(URL_RE) || []).length;
  // צורך "חזק" (סיפור אישי / השירות שלי) גובר על הכל. מילים כלליות ("פרטים", "מחיר", "לקבוע")
  // מופיעות גם בפרסומות — הן מספיקות רק כשאין בהודעה שום סימן של פרסום.
  const strong = NEED.some(w => !WEAK.includes(w) && t.includes(w)) || extraWords.some(w => w && t.includes(w));
  const weak = WEAK.some(w => t.includes(w));
  const promoWords = PROMO.filter(w => t.includes(w)).length;
  const need = strong || (weak && !promoWords);

  if (SPAM.some(r => r.test(t)) && !need) return "spam";
  if (urls >= 2 && !need) return "spam";
  if (AUTOMATED.some(r => r.test(t)) && !strong && !INTEREST.some(w => t.includes(w))) return "auto";

  let score = promoWords;
  if (urls) score++;
  if (PHONE_RE.test(t)) score++;
  if ((t.match(EMOJI_RE) || []).length >= 4) score++;
  if (t.length > 300) score++;
  if (!need && score >= 2) return "promo";
  if (!need && score >= 1) return "promo";
  if (!need && t.replace(/\s+/g, " ").trim().length > 60) return "irrelevant";
  return "normal";
}

const YES = /^(כן|בטח|ברור|כמובן|אשמח|מעוניינ|נשמע טוב|למה לא|אולי)/;
const NO = /^(לא|לא תודה|ממש לא|לא רלוונטי|טעות)/;
export const isYes = (t) => YES.test(String(t || "").trim());
export const isNo = (t) => NO.test(String(t || "").trim());
