const URL_RE = /(https?:\/\/|www\.)\S+/gi;
const PHONE_RE = /(?:\+?972|0)[\s-]?\d{1,2}[\s-]?\d{3}[\s-]?\d{4}/;
const EMOJI_RE = /\p{Extended_Pictographic}/gu;

