/**
 * "spam" | "auto" | "promo" | "normal".
 * hints.business: השולח הוא חשבון עסקי (וואטסאפ ביזנס) — עוד סימן לפרסום/הודעה אוטומטית.
 */
// ניסוחים של לקוח/ה שמתעניין/ת בשירות (לכל סוג עסק)
const INTEREST = ["יש לכם", "אתם עושים", "את עושה", "אתה עושה", "כמה עולה", "כמה זה עולה", "מחיר", "אשמח", "מעוניינ", "רציתי לשאול", "רציתי לברר", "אפשר לקבוע", "אפשר פרטים", "לקבל פרטים"];

export function classifyMessage(text, hints = {}) {
  const t = String(text || "").toLowerCase();
  if (!t.trim()) return "normal";
  const urls = (t.match(URL_RE) || []).length;
  const need = NEED.some(w => t.includes(w));

  if (SPAM.some(r => r.test(t)) && !need) return "spam";
  if (urls >= 2 && !need) return "spam";
  // "יש לכם משלוחים?" של לקוח/ה לעסק שעושה משלוחים — זו התעניינות, לא שליח.
  if (AUTOMATED.some(r => r.test(t)) && !need && !INTEREST.some(w => t.includes(w))) return "auto";

  let score = PROMO.filter(w => t.includes(w)).length;
  if (urls) score++;
  if (PHONE_RE.test(t)) score++;
  if ((t.match(EMOJI_RE) || []).length >= 4) score++;
  if (t.length > 300) score++;
  if (hints.business) score++;
  if (!need && score >= 2) return "promo";
  return "normal";
}

const YES = /^(כן|בטח|ברור|כמובן|אשמח|מעוניינ|נשמע טוב|למה לא|אולי)/;
const NO = /^(לא|לא תודה|ממש לא|לא רלוונטי|טעות)/;
export const isYes = (t) => YES.test(String(t || "").trim());
export const isNo = (t) => NO.test(String(t || "").trim());
