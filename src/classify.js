//               מתעניין בשירות, ומפנים לאתר. אם ממשיך לפרסם — מתעלמים.
//   • "normal"— פנייה רגילה: עונים כרגיל (ומובילים לשיחת היכרות כשמתאים).
//  זהיר בכוונה: עדיף לענות לפרסום מאשר לפספס אדם אמיתי. כל סימן של צורך אישי
//  ("קשה לי", "הבת שלי", "אשמח לפרטים על הליווי") הופך את ההודעה לרגילה.
