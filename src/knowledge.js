/**
 * מנתב פנייה נכנסת לסעיפי בסיס הידע הרלוונטיים.
 * @returns {{sections: string[], context: string}}
 */
export function routeToKnowledge(text) {
  const t = (text || "").toLowerCase();
  const hits = KNOWLEDGE
    .map(section => ({
      section,
      score: section.keywords.reduce((n, k) => n + (t.includes(k) ? 1 : 0), 0)
    }))
    .filter(h => h.score > 0)
    .sort((a, b) => b.score - a.score)
    .slice(0, 3);

  return {
    sections: hits.map(h => h.section.id),
    context: hits.map(h => `### ${h.section.title}\n${h.section.text}`).join("\n\n")
  };
}
